package handlers

import (
	"fmt"
	"net/http"

	"github.com/gin-gonic/gin"
)

func GenerateConfig(c *gin.Context) {
	var body struct {
		AgentType      string `json:"agent_type"`
		Endpoint       string `json:"endpoint"`
		CaptureContent bool   `json:"capture_content"`
	}

	if err := c.ShouldBindJSON(&body); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "invalid request body"})
		return
	}

	if body.Endpoint == "" {
		body.Endpoint = "https://otel.timeplus.io:4317"
	}

	captureStr := "false"
	if body.CaptureContent {
		captureStr = "true"
	}

	var config string
	switch body.AgentType {
	case "openclaw":
		config = generateOpenclawConfig(body.Endpoint, captureStr)
	case "claude_code":
		config = generateClaudeCodeConfig(body.Endpoint, captureStr)
	default:
		c.JSON(http.StatusBadRequest, gin.H{"error": "agent_type must be 'openclaw' or 'claude_code'"})
		return
	}

	c.JSON(http.StatusOK, gin.H{
		"agent_type": body.AgentType,
		"endpoint":   body.Endpoint,
		"config":     config,
	})
}

